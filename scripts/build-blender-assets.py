"""Builds site/assets/blender/* and site/blender/data.js from the original Blender exports.
Run:  python scripts/build-blender-assets.py "<folder with the extracted blender zip>"
Needs Pillow and imageio-ffmpeg (pip install pillow imageio-ffmpeg). The originals are not stored in the repo."""
import json, os, subprocess, sys
from PIL import Image, ImageOps, ImageFilter, ImageChops
import imageio_ffmpeg

SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), "..", "site", "assets", "blender")
os.makedirs(OUT, exist_ok=True)
FF = imageio_ffmpeg.get_ffmpeg_exe()

# id, title, folder, files (first one is the cover), note
PROJECTS = [
    ("airpods", "AirPods Max", "headphone", ["airpods max3.png", "airpods max4.png", "airpods max2.png", "airpods max.png"]),
    ("lambo-wheel", "Lamborghini steering wheel", "lambowheel", ["lambowheel3.png", "lambowheel1.png", "lambowheel2.png"]),
    ("microphone", "Studio microphone", "microphone", ["untitled5.png", "untitled.png", "untitled2.png", "untitled3.png", "untitled4.png"]),
    ("perfume", "Perfume bottle", "Perfume bottle 3d", ["perfume splash.png", "PERFUME.png"]),
    ("spider", "Spider robot", "spiderman", ["1.png", "2.png"]),
    ("rifle", "Rifle study", "gun", ["4.png", "untitled.png", "2.png", "3.png", "5.png"]),
]
VIDEOS = [
    ("bugatti", "Bugatti Chiron trailer", "Bugatti Chiron Trailer.mp4", 26),
    ("volvo", "Volvo ad", "Volvo Ad.mp4", 19),
]

def webp(src, dst, width, q):
    im = Image.open(src).convert("RGB")
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    im.save(dst, "WEBP", quality=q, method=6)
    return im.size


data = {"projects": [], "videos": []}
for pid, title, folder, files in PROJECTS:
    shots = []
    for i, f in enumerate(files, 1):
        base = f"{pid}-{i}"
        w, h = webp(os.path.join(SRC, folder, f), os.path.join(OUT, base + "-t.webp"), 800, 80)
        webp(os.path.join(SRC, folder, f), os.path.join(OUT, base + ".webp"), 1600, 82)
        shots.append({"src": f"assets/blender/{base}.webp", "thumb": f"assets/blender/{base}-t.webp", "w": w * 2, "h": h * 2})
    data["projects"].append({"id": pid, "title": title, "shots": shots})

for vid, title, f, poster_at in VIDEOS:
    src = os.path.join(SRC, f)
    mp4 = os.path.join(OUT, vid + ".mp4")
    subprocess.run([FF, "-y", "-loglevel", "error", "-i", src, "-vf", "scale=1280:-2", "-c:v", "libx264", "-crf", "27", "-preset", "slow",
                    "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-c:a", "aac", "-b:a", "96k", mp4], check=True)
    poster = os.path.join(OUT, vid + "-poster.webp")
    tmp = os.path.join(OUT, vid + "-poster.png")
    subprocess.run([FF, "-y", "-loglevel", "error", "-ss", str(poster_at), "-i", src, "-frames:v", "1", "-vf", "scale=1280:-2", tmp], check=True)
    webp(tmp, poster, 1280, 82); os.remove(tmp)
    data["videos"].append({"id": vid, "title": title, "src": f"assets/blender/{vid}.mp4", "poster": f"assets/blender/{vid}-poster.webp"})

js = "/* Generated by build-assets.py. Edit titles here; re-run the script only when the source renders change. */\nexport const BLENDER = " + json.dumps(data, indent=2) + ";\n"
open(os.path.join(os.path.dirname(__file__), "..", "site", "blender", "data.js"), "w", encoding="utf-8").write(js)
total = sum(os.path.getsize(os.path.join(OUT, n)) for n in os.listdir(OUT))
print("ok", len(os.listdir(OUT)), "files,", round(total / 1e6, 1), "MB")
